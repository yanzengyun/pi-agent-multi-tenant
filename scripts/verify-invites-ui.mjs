  assert.match(invitation.url, /\/join#invite=/);
  const account = await browser.newContext(), member = await account.newPage(), errors = [];
  member.on('pageerror', e => errors.push(e.name)); await member.goto(invitation.url);
  await member.locator('#register').waitFor({ state: 'visible' });
  const username = 'verify_ui_' + Date.now(), password = 'fake-registration-password-28';
  await member.locator('#register-form input[name=username]').fill(username);
  await member.locator('#register-form input[name=password]').fill(password);
  const registered = member.waitForResponse(r => r.url().endsWith('/api/register') && r.request().method() === 'POST');
  await member.locator('#register-form button').click(); const result = await registered;
  assert.equal(result.status(), 201); user = { ...(await result.json()).user, _inviteId: invitation.id };
  await member.locator('#account').waitFor({ state: 'visible' });
  assert.equal((await account.request.get(login.url + 'api/admin/users')).status(), 401);
