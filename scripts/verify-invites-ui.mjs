  assert.equal((await account.request.get(login.url + 'api/account')).status(), 401);
  await member.locator('#login-form input[name=username]').fill(username);
  await member.locator('#login-form input[name=password]').fill('fake-changed-password-38');
  await member.locator('#login-form button').click(); await member.locator('#account').waitFor({ state: 'visible' });
  assert.equal(await member.locator('#agents-content').inputValue(), preferences);
  const freshNotes = await browser.newContext(), afterRotation = await freshNotes.newPage();
  await afterRotation.goto(notesUrl); await afterRotation.locator('input[name=username]').fill(notesUsername);
  await afterRotation.locator('input[type=password]').fill('fake-changed-password-38');
  await afterRotation.getByRole('button',{name:'Log in',exact:true}).click();
  await afterRotation.waitForURL(url=>url.pathname.startsWith('/users/'+user.id+'/') && !url.pathname.includes('/.auth'));
  assert.equal((await freshNotes.request.get(notesUrl+'.fs/index.md')).status(),200); await freshNotes.close();
