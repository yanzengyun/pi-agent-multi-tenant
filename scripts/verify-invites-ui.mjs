  await member.locator('#agents-content').fill(preferences); await member.locator('#agents-form button').click();
  await member.getByText('人物设定已保存，后续对话生效。', { exact: true }).waitFor();
  assert.equal((await (await account.request.get(login.url + 'api/account/agents')).json()).content, preferences);
  const drafted = member.waitForResponse(r => r.url().endsWith('/api/account/persona-assist') && r.request().method() === 'POST');
  await member.locator('#persona-assist-form textarea').fill('只写一行：我是一个用中文简短回答的个人助手。');
  await member.locator('#persona-assist-form button').click(); const draftRun = await (await drafted).json();
  await member.getByText('草稿已生成，请检查后点击“保存人物设定”。', {exact:true}).waitFor({timeout:150000});
  assert.equal((await (await account.request.get(login.url + 'api/account/agents')).json()).content, preferences);
  const events = await (await admin.request.get(login.url + 'api/admin/users/' + user.id + '/runs/' + draftRun.id + '/trace')).json();
  assert.deepEqual(events.events.find(e=>e.kind==='context').payload.activeTools,['persona_read']);
  const notesUsername = username + '_notes', notesPassword = password;
  await member.locator('#notes-form input[name=username]').fill(notesUsername);
  await member.locator('#notes-form input[name=password]').fill(notesPassword);
  await member.locator('#notes-form button').click();
  await member.getByText('笔记已更新，密码与主页一致，原笔记保留。', { exact: true }).waitFor({ timeout: 60000 });
  await member.locator('#notes-link').waitFor({ state: 'visible' });
  const notesUrl = await member.locator('#notes-link').getAttribute('href');
  const details = await admin.request.post(login.url + 'api/admin/users/' + user.id + '/silverbullet/credentials', { data: {} });
  assert.equal(details.status(), 200); const credentials = await details.json();
  assert.equal(credentials.password, null); assert.equal(credentials.passwordManagedByUser, true);
  const notes = await account.newPage(), challenges = [];
  notes.on('response', response => { if (response.headers()['www-authenticate']) challenges.push(response.url()); });
  await notes.goto(notesUrl);
  await notes.locator('input[name=username]').fill(notesUsername); await notes.locator('input[type=password]').fill(notesPassword);
  await notes.getByRole('button', { name: 'Log in', exact: true }).click();
  await notes.waitForURL(url => url.pathname.startsWith('/users/' + user.id + '/') && !url.pathname.includes('/.auth'));
  assert.equal((await account.request.get(notesUrl + '.fs/index.md')).status(), 200);
  assert.deepEqual(challenges, []); await notes.close();
